function wrap(d: number, n: number) { return ((d + n / 2) % n + n) % n - n / 2 }
function place(i: number, n: number, off: number) {
  const d = wrap(i - off, n)
  return {x:d*SPACING,y:0,z:-Math.abs(d)*14,ry:0,rx:0,rz:0,
    sc:Math.max(.6,1-Math.abs(d)*SCALE_STEP),op:Math.max(.4,1-Math.abs(d)/7),blur:Math.min(.8,Math.abs(d)*.14)};
}

